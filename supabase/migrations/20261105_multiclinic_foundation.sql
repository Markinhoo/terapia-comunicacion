create or replace function public.audit_table_change()
returns trigger
language plpgsql security definer
set search_path = public, auth
as $$
declare
  v_before jsonb;
  v_after jsonb;
  v_row jsonb;
  v_fields text[];
  v_email text;
begin
  -- Public bookings have no staff actor. Their data must not be copied into
  -- an administrator audit trail.
  if auth.uid() is null then
    return coalesce(new, old);
  end if;

  v_before := case when tg_op <> 'INSERT' then to_jsonb(old) else '{}'::jsonb end;
  v_after := case when tg_op <> 'DELETE' then to_jsonb(new) else '{}'::jsonb end;
  v_row := case when tg_op = 'DELETE' then v_before else v_after end;

  if tg_op = 'UPDATE' then
    select coalesce(array_agg(key order by key), array[]::text[])
    into v_fields
    from jsonb_object_keys(v_after - 'updated_at') as key
    where (v_before -> key) is distinct from (v_after -> key);

    if cardinality(v_fields) = 0 then
      return new;
    end if;
  else
    v_fields := array[]::text[];
  end if;

  select email into v_email from auth.users where id = auth.uid();

  insert into public.bitacora_cambios (
    clinica_id, tabla, registro_id, accion, usuario_id, usuario_email,
    descripcion, cambios
  ) values (
    (v_row ->> 'clinica_id')::uuid,
    tg_table_name,
    v_row ->> 'id',
    tg_op,
    auth.uid(),
    v_email,
    format('%s en %s, registro %s%s.',
      case tg_op when 'INSERT' then 'Alta' when 'UPDATE' then 'Cambio' else 'Baja' end,
      tg_table_name,
      coalesce(v_row ->> 'id', '-'),
      case when cardinality(v_fields) > 0
        then ' (campos: ' || array_to_string(v_fields, ', ') || ')'
        else '' end
    ),
    jsonb_build_object('campos', v_fields)
  );

  return coalesce(new, old);
end;
$$;

