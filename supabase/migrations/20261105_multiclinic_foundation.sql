-- Keep the existing foreign keys so PostgREST relationships remain unique.
-- Validate the tenant on every new or edited child row instead.
create or replace function public.validar_clinica_paciente()
returns trigger
language plpgsql security definer
set search_path = pg_catalog, public
as $$
declare
  v_clinica_id uuid;
begin
  if new.paciente_id is not null then
    select clinica_id into v_clinica_id
    from public.pacientes where id = new.paciente_id;
    if v_clinica_id is distinct from new.clinica_id then
      raise exception using errcode = '42501', message = 'El paciente pertenece a otra clínica.';
    end if;
  end if;

  if tg_table_name = 'envios_reglamento' then
    select clinica_id into v_clinica_id
    from public.citas where id = new.cita_id;
    if v_clinica_id is distinct from new.clinica_id then
      raise exception using errcode = '42501', message = 'La cita pertenece a otra clínica.';
    end if;
  end if;

  return new;
end;
$$;

do $$
declare
  v_table text;
begin
  foreach v_table in array array[
    'citas', 'paciente_detalle', 'expedientes', 'paciente_objetivos',
    'archivos_paciente', 'sesiones_paciente', 'envios_reglamento'
  ] loop
    if to_regclass(format('public.%I', v_table)) is not null
       and exists (
         select 1 from information_schema.columns
         where table_schema = 'public' and table_name = v_table
           and column_name = 'paciente_id'
       ) then
      execute format('drop trigger if exists tenant_patient_match on public.%I', v_table);
      execute format('create trigger tenant_patient_match before insert or update on public.%I for each row execute function public.validar_clinica_paciente()', v_table);
    end if;
  end loop;
end $$;

-- Replace permissive historical policies; tenant isolation must be server-side.
do $$
declare
  v_table text;
  v_policy record;
begin
  foreach v_table in array array[
    'pacientes', 'citas', 'paciente_detalle', 'expedientes',
    'paciente_objetivos', 'objetivos_terapeuticos', 'archivos_paciente',
    'sesiones_paciente', 'envios_reglamento', 'galeria_terapias',
    'galeria_likes', 'invitaciones_usuario', 'bitacora_cambios',
    'servicios_clinica', 'app_profiles', 'clinicas'
  ] loop
    execute format('alter table public.%I enable row level security', v_table);
    for v_policy in
      select policyname from pg_policies
      where schemaname = 'public' and tablename = v_table
    loop
      execute format('drop policy %I on public.%I', v_policy.policyname, v_table);
    end loop;
  end loop;

  foreach v_table in array array[
    'pacientes', 'citas', 'paciente_detalle', 'expedientes',
    'paciente_objetivos', 'objetivos_terapeuticos', 'archivos_paciente',
    'sesiones_paciente', 'envios_reglamento'
  ] loop
    if v_table = 'citas' then
      execute format('create policy tenant_read on public.%I for select to authenticated using (clinica_id = public.clinica_actual())', v_table);
    else
      execute format('create policy tenant_read on public.%I for select to authenticated using (public.puede_editar_clinica(clinica_id))', v_table);
    end if;
    execute format('create policy tenant_insert on public.%I for insert to authenticated with check (public.puede_editar_clinica(clinica_id))', v_table);
    execute format('create policy tenant_update on public.%I for update to authenticated using (public.puede_editar_clinica(clinica_id)) with check (public.puede_editar_clinica(clinica_id))', v_table);
    execute format('create policy tenant_delete on public.%I for delete to authenticated using (public.puede_editar_clinica(clinica_id))', v_table);
  end loop;
end $$;

