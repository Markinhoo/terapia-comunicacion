create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql security definer
set search_path = public, auth
as $$
declare
  v_clinica_id uuid;
begin
  -- app_metadata is set only by a trusted service-role call. Accounts without
  -- a clinic assignment cannot enter a clinic panel.
  v_clinica_id := nullif(new.raw_app_meta_data ->> 'clinica_id', '')::uuid;
  if v_clinica_id is not null then
    insert into public.app_profiles (id, email, role, clinica_id)
    values (new.id, coalesce(new.email, ''), 'user', v_clinica_id)
    on conflict (id) do nothing;
  end if;
  return new;
end;
$$;

